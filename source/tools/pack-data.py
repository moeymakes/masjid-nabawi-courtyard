#!/usr/bin/env python3
"""Pack captured real-world data into source/src/data.js (realism stage 3). Run with python3 -I.

  python3 -I tools/pack-data.py <Copernicus GLO-30 N24_E039 .tif> > src/data.js

DEM: Copernicus GLO-30 (c) DLR e.V. 2010-2014 and (c) Airbus Defence and Space GmbH 2014-2018, provided under
COPERNICUS by the European Union and ESA; free and open.
"""
import sys, base64
import numpy as np
from PIL import Image

dem = np.asarray(Image.open(sys.argv[1]), dtype=np.float32)  # 3600x3600, rows 25N -> 24N, cols 39E -> 40E


def patch(name, lat0, lat1, lon0, lon1, w, h, base, step):
    # sample on a regular lat/lon grid (row 0 = north), heights above `base` in `step` m, 8 bit
    out = np.zeros((h, w), np.uint8)
    for j in range(h):
        lat = lat1 - (lat1 - lat0) * j / (h - 1)
        for i in range(w):
            lon = lon0 + (lon1 - lon0) * i / (w - 1)
            r, c = (25 - lat) * 3600, (lon - 39) * 3600
            r0, c0 = int(r), int(c); fr, fc = r - r0, c - c0
            v = (dem[r0, c0] * (1 - fc) + dem[r0, c0 + 1] * fc) * (1 - fr) + (dem[r0 + 1, c0] * (1 - fc) + dem[r0 + 1, c0 + 1] * fc) * fr
            out[j, i] = max(0, min(255, round((v - base) / step)))
    b64 = base64.b64encode(out.tobytes()).decode()
    return f"const {name} = {{ lat0: {lat0}, lat1: {lat1}, lon0: {lon0}, lon1: {lon1}, w: {w}, h: {h}, base: {base}, step: {step}, b64: '{b64}' }};"


print('// ============================================================================')
print('// captured real-world data (realism stage 3), generated by tools/pack-data.py: do not edit by hand')
print('// ============================================================================')
print('// Elevation: Copernicus GLO-30 DEM (ESA / Airbus, free and open), mapped into the world\'s composed (not to')
print('// scale) geography in shaders.js.')
print(patch('DEM_UHUD', 24.495, 24.55, 39.57, 39.68, 112, 56, 590, 2))
print(patch('DEM_AYR', 24.355, 24.42, 39.50, 39.62, 88, 48, 600, 2))

